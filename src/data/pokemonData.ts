export const STARTER_IDS = ['charmander', 'squirtle', 'bulbasaur', 'pikachu', 'riolu', 'gastly', 'gible', 'eevee'];

export function calculateStats(base: SpeciesData['baseStats'], level: number): SpeciesData['baseStats'] {
  const hp = Math.floor(((2 * base.hp + 31) * level) / 100) + level + 10;
  const calc = (b: number) => Math.floor(((2 * b + 31) * level) / 100) + 5;
  return {
    hp,
    atk: calc(base.atk),
    def: calc(base.def),
    spa: calc(base.spa),
    spd: calc(base.spd),
    spe: calc(base.spe),
  };
}

export function createPokemon(speciesId: string, level: number = 5, isShiny: boolean = false): PokemonInstance {
  const species = POKEMON_SPECIES[speciesId] || POKEMON_SPECIES.charmander;
  const stats = calculateStats(species.baseStats, level);

  // Initialize moves from species learnset up to current level
  const validMoves = species.learnableMoves
    .filter((m) => m.level <= level)
    .slice(-4);

  const moves: MoveInstance[] = (validMoves.length > 0 ? validMoves : [{ level: 1, moveId: 'tackle' }])
    .map((m) => {
      const baseMove = MOVES[m.moveId] || MOVES.tackle;
      return {
        ...baseMove,
        currentPp: baseMove.maxPp,
      };
    });

  const uid = `pkm_${speciesId}_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`;

  return {
    uid,
    speciesId: species.id,
    pokedexNo: species.pokedexNo,
    name: species.name,
    nameZh: species.nameZh,
    types: [...species.types],
    level,
    exp: 0,
    maxExp: level * 25,
    currentHp: stats.hp,
    maxHp: stats.hp,
    stats,
    statStages: { atk: 0, def: 0, spa: 0, spd: 0, spe: 0 },
    moves,
    status: 'None',
    isShiny,
    ability: { ...species.ability },
    accentColor: species.accentColor,
  };
}
